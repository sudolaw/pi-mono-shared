        versionName = flutter.versionName
    }

    // CI passes a fixed keystore so every APK has the same signature and can be
    // installed over the previous one. Without it, the debug key is used.
    val keystorePath = System.getenv("NUDGE_KEYSTORE_PATH")
    signingConfigs {
        if (keystorePath != null) {
            create("release") {
                storeFile = file(keystorePath)
                storePassword = System.getenv("NUDGE_KEYSTORE_PASSWORD")
                keyAlias = System.getenv("NUDGE_KEY_ALIAS")
                keyPassword = System.getenv("NUDGE_KEY_PASSWORD")
            }
        }
    }

    buildTypes {
        release {
            signingConfig =
                if (keystorePath != null) signingConfigs.getByName("release")
                else signingConfigs.getByName("debug")
        }
    }
